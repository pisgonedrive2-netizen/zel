export function packageTagline(copy: LandingCopy, id: string, fallback: string): string {
  if (id === "starter") return copy.taglineStarter;
  if (id === "standard") return copy.taglineStandard;
  if (id === "premium") return copy.taglinePremium;
  if (id === "elite") return copy.taglineElite;
  if (id === "multi") return copy.taglineMulti;
  return fallback;
}
