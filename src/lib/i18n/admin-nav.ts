export function adminGroupLabel(locale: AppLocale, group: string): string {
  const key = `group_${group.replace(/ /g, "_")}`;
  return adminNavLabel(locale, key, group);
}

export function adminNavLabel(locale: AppLocale, key: string, fallback: string): string {
  const dict = locale === "ru" ? RU : TR;
  return dict[key] ?? fallback;
}
